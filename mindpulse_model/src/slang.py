def normalize_slang(text: str) -> str:

    import re

    # ── Multi-word phrases first (order matters) ─────────────
    MULTI_WORD = {
        "no cap":       "honestly",
        "big W":        "great win",
        "big L":        "big loss",
        "fr fr":        "very seriously",
        "feels bad man":"feeling very sad",
        "feels bad":    "feeling sad",
        "ate that":     "did very well",
        "hits different":"feels really good",
        "bruh moment":  "surprising unexpected moment",
        "plot twist":   "unexpected surprise",
        "wait what":    "I am surprised",
        "wait wut":     "I am surprised",
        "no way":       "I cannot believe this",
        "scared af":    "very scared",
        "nervous af":   "very nervous",
        "im shaking":   "I am very nervous",
        "i'm shaking":  "I am very nervous",
        "im dead":      "I am laughing very hard",
        "i'm dead":     "I am laughing very hard",
        "understood the assignment": "did very well",
        "sending me":   "making me laugh",
    }

    text_lower = text.lower()
    for phrase, replacement in MULTI_WORD.items():
        if phrase in text_lower:
            text = re.sub(re.escape(phrase), replacement, text, flags=re.IGNORECASE)

    # ── Single words ─────────────────────────────────────────
    words = text.split()
    normalized = []
    for word in words:
        clean = re.sub(r"[^\w]", "", word).lower()
        if clean in SLANG_MAP:
            normalized.append(SLANG_MAP[clean])
        else:
            normalized.append(word)

    return " ".join(normalized)